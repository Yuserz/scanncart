// Does this repo still speak pushcart-web's POS routes?
//
// The desktop's half of the integration is a contract with a codebase in another checkout: two route
// paths, a header name, and the status codes the routes answer in. Nothing in this repo can notice
// when that codebase moves. The stand-in in `src/main/posWebappStandIn.ts` was written from
// pushcart-web's files and would happily keep answering the old shape, and
// `src/main/posRoutes.integration.test.ts` would go on passing, because it tests the stand-in against
// the client that was written beside it — both halves moving together is exactly the drift it cannot
// see.
//
// So this reads the contract out of pushcart-web's own route source and compares it with the copy
// this repo keeps (`src/main/posContract.json`). That copy is what the suite checks `posClient.ts`
// and the stand-in against — `src/main/posContract.test.ts`, which runs on a bare checkout — and
// running this is what keeps the copy from going stale.
//
// There are two copies of that contract, not one: pushcart-web derives and records the same surface
// from its own routes (by `scripts/pos-contract.mjs` there), and each copy is checked against its own
// source. A one-sided `--write` — this repo re-recording after a deliberate change without
// pushcart-web re-recording its own — leaves *both* of those green while the two repos describe
// different routes, which is the one failure neither repo's own guard can see. So the two records are
// compared as well, here, because this is the only job that has both trees in hand.
//
// It needs `../pushcart-web`, which this repo does not carry, so it is not in `make test`, and it
// fails loudly (exit 2) when the checkout — or the record pushcart-web keeps in it — is absent rather
// than skipping: a comparison against a copy that is not there is the pass that would read as "the
// two repos agree". The extraction is read as
// text rather than parsed: these files import Supabase and Next's request types, and a regex over
// four small files is the price of not dragging a TypeScript build of another app into this one. A
// shape this does not recognise is an error naming the file, never a silent empty contract.
//
// Run it with `make verify-pos-contract`, or directly:
//     cd desktop && node scripts/check-pos-contract.mjs
// Regenerate the copy after a deliberate pushcart-web change:
//     cd desktop && node scripts/check-pos-contract.mjs --write
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url)) // desktop/scripts
const desktop = join(here, '..')
const repoRoot = join(desktop, '..')
const CONTRACT = join(desktop, 'src', 'main', 'posContract.json')
const APP_POS = 'app/api/pos'
const RESPONSE_HELPERS = join('app', 'api', 'helpers', 'response.ts')
const RECONCILE = join('app', 'api', 'model', 'pos_sync.ts')

const NOTE =
  "Generated by desktop/scripts/check-pos-contract.mjs from pushcart-web's route source. Do not " +
  'edit by hand: run `make verify-pos-contract POS_CONTRACT_ARGS=--write`.'

function valueAfter(flag) {
  const index = process.argv.indexOf(flag)
  if (index === -1) return null
  const value = process.argv[index + 1]
  if (!value || value.startsWith('--')) {
    console.error(`check-pos-contract: ${flag} needs a directory`)
    process.exit(2)
  }
  return value
}

const WRITE = process.argv.includes('--write')
const pushcart =
  valueAfter('--pushcart') ?? process.env.PUSHCART_WEB_DIR ?? join(repoRoot, '..', 'pushcart-web')

if (!existsSync(join(pushcart, APP_POS))) {
  console.error(`check-pos-contract: no pushcart-web checkout at ${pushcart}`)
  console.error('check-pos-contract: it is a separate checkout — point at it with --pushcart <dir>')
  console.error('check-pos-contract: or PUSHCART_WEB_DIR. Nothing was checked.')
  process.exit(2)
}

const read = (...parts) => readFileSync(join(pushcart, ...parts), 'utf8')

/** Every desktop-facing route, by the path Next.js derives from the directory it lives in. */
function routes() {
  const dir = join(pushcart, APP_POS)
  const out = {}
  for (const segment of readdirSync(dir).sort()) {
    const file = join(dir, segment, 'route.ts')
    if (!existsSync(file)) continue
    const handler = /export async function (\w+)/.exec(readFileSync(file, 'utf8'))
    if (!handler) throw new Error(`no exported handler in ${APP_POS}/${segment}/route.ts`)
    out[`/api/pos/${segment}`] = handler[1]
  }
  if (Object.keys(out).length === 0) throw new Error(`no route files under ${APP_POS}`)
  return out
}

/** The header the routes authenticate with, read from them because they are where it is decided. */
function authHeader() {
  const dir = join(pushcart, APP_POS)
  const found = new Set()
  for (const segment of readdirSync(dir)) {
    const file = join(dir, segment, 'route.ts')
    if (!existsSync(file)) continue
    const header = /headers\.get\(\s*['"]([^'"]+)['"]\s*\)/.exec(readFileSync(file, 'utf8'))
    if (header) found.add(header[1])
  }
  if (found.size !== 1) {
    throw new Error(
      `the POS routes do not agree on one auth header: ${found.size === 0 ? 'none found' : [...found].join(', ')}`
    )
  }
  return [...found][0]
}

/** `response.ts`'s helper -> its status: the vocabulary every route answers in. */
function statuses() {
  const out = {}
  for (const body of read(RESPONSE_HELPERS).split('export function ').slice(1)) {
    const name = /^(\w+)/.exec(body)?.[1]
    const status = /status:\s*(\d+)/.exec(body)?.[1]
    if (name && status) out[name] = Number(status)
  }
  if (Object.keys(out).length === 0) {
    throw new Error(`no response helper statuses found in ${RESPONSE_HELPERS}`)
  }
  return out
}

/** The reconcile's failure codes -> the helper each answers with, from `mapError`'s switch. */
function outcomes() {
  const body = /const mapError[\s\S]*?\n};/.exec(read(RECONCILE))?.[0]
  if (!body) throw new Error(`no mapError switch found in ${RECONCILE}`)

  const out = {}
  let pending = []
  for (const line of body.split('\n')) {
    const label = /^\s*case '([^']+)':\s*$/.exec(line)?.[1] ?? /^\s*(default):\s*$/.exec(line)?.[1]
    if (label) {
      pending.push(label)
      continue
    }
    const returned = /^\s*return (\w+)\(/.exec(line)?.[1]
    if (returned && pending.length > 0) {
      // One `return` can serve several stacked `case`s — the whole conflict family shares one.
      for (const key of pending) out[key] = returned
      pending = []
    }
  }
  if (Object.keys(out).length === 0) throw new Error(`no error cases found in ${RECONCILE}`)
  return out
}

function derive() {
  return {
    auth_header: authHeader(),
    note: NOTE,
    outcomes: outcomes(),
    routes: routes(),
    statuses: statuses()
  }
}

/** Keys in a fixed order at every level, so the file is stable and a diff is the contract moving. */
function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical)
  if (value !== null && typeof value === 'object') {
    const sorted = {}
    for (const key of Object.keys(value).sort()) sorted[key] = canonical(value[key])
    return sorted
  }
  return value
}

const render = (value) => `${JSON.stringify(canonical(value), null, 2)}\n`

let derived
try {
  derived = derive()
} catch (error) {
  console.error(`check-pos-contract: ${error.message}`)
  console.error(
    'check-pos-contract: the extraction is what broke, so nothing was compared. This is'
  )
  console.error(
    'check-pos-contract: the one failure that is about this script rather than the contract.'
  )
  process.exit(1)
}

if (WRITE) {
  writeFileSync(CONTRACT, render(derived))
  console.log(`check-pos-contract: wrote ${CONTRACT}`)
} else {
  if (!existsSync(CONTRACT)) {
    console.error(`check-pos-contract: no recorded contract at ${CONTRACT}`)
    console.error('check-pos-contract: create it with --write (see `make verify-pos-contract`).')
    process.exit(1)
  }

  const recorded = JSON.parse(readFileSync(CONTRACT, 'utf8'))
  const drifted = Object.keys(derived).filter(
    (key) => render(derived[key]) !== render(recorded[key])
  )

  if (drifted.length > 0) {
    console.error(`check-pos-contract: the recorded contract no longer matches ${pushcart}`)
    for (const key of drifted) {
      console.error(`  ${key}:`)
      console.error(`    pushcart-web:  ${JSON.stringify(canonical(derived[key]))}`)
      console.error(`    recorded here: ${JSON.stringify(canonical(recorded[key]))}`)
    }
    console.error(
      'check-pos-contract: a deliberate pushcart-web change is one --write away; anything'
    )
    console.error(
      'check-pos-contract: else means this repo is speaking a route that is no longer there.'
    )
    process.exit(1)
  }

  // This repo's copy is a fresh reading of pushcart-web's source, so it says nothing about the copy
  // pushcart-web keeps: a change recorded on one side only leaves both guards green on their own
  // terms. Comparing the two records is what closes that, and it can only happen here.
  //
  // `note` is deliberately not compared. It names the script that generated the file, so it differs
  // between the two by design and describes provenance rather than the surface.
  const SIBLING_RECORD = join(pushcart, 'scripts', 'pos-contract.json')
  const COMPARED = ['auth_header', 'outcomes', 'routes', 'statuses']

  if (!existsSync(SIBLING_RECORD)) {
    console.error(`check-pos-contract: pushcart-web records no contract at ${SIBLING_RECORD}`)
    console.error('check-pos-contract: it is the other half of this comparison, so nothing was')
    console.error('check-pos-contract: compared. Point at a checkout that carries one.')
    process.exit(2)
  }

  const sibling = JSON.parse(readFileSync(SIBLING_RECORD, 'utf8'))
  const disagree = COMPARED.filter((key) => render(recorded[key]) !== render(sibling[key]))

  if (disagree.length > 0) {
    console.error('check-pos-contract: this repo and pushcart-web recorded different contracts')
    for (const key of disagree) {
      console.error(`  ${key}:`)
      console.error(`    pushcart-web:  ${JSON.stringify(canonical(sibling[key]))}`)
      console.error(`    recorded here: ${JSON.stringify(canonical(recorded[key]))}`)
    }
    console.error(
      'check-pos-contract: each repo records its own copy, so one of them has not been re-recorded.'
    )
    console.error(
      'check-pos-contract: a deliberate change needs a --write on both sides; nothing else moves'
    )
    console.error('check-pos-contract: a record nobody regenerated.')
    process.exit(1)
  }

  const routeCount = Object.keys(derived.routes).length
  const statusCount = Object.keys(derived.statuses).length
  console.log(`check-pos-contract: ${CONTRACT} matches ${pushcart}`)
  console.log(
    `check-pos-contract: ${routeCount} route(s), ${statusCount} status(es), ` +
      `auth header "${derived.auth_header}"`
  )
  console.log(`check-pos-contract: the two recorded contracts agree on ${COMPARED.length} key(s)`)
}
