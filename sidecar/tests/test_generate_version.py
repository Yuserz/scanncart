def test_the_preflight_prints_what_a_version_would_bake_in(monkeypatch, capsys):
    """The one-shot decision, in one read and before it is spent: the class list *in order* (the
    export's indices), the geometry being sent, and how many of the project's images carry a
    decision - which is what the version will contain, because only annotated images enter one.

    A set that is not finished is a **warning** and not a gate: a partial version is a legitimate
    intermediate (and how the set comes back if the labels have to be redone on the server), so what
    it needs is the number in front of the operator, not a refusal.
    """
    roster = {name: i for i, name in enumerate(label_classes.SLUG_TO_CLASS.values())}
    fake = _generator(monkeypatch, roster, _annotated(2, nulls=1, unlabeled=1))

    assert generate_version.main(["--yes", "--project", "snc-grocery"]) == 0
    out = capsys.readouterr().out

    assert "project snc-grocery" in out
    assert "  classes  : 7, in v2's order" in out
    assert "   1  " + generations.V2.classes[0] in out  # numbered, so the order is readable
    assert "  settings : auto-orient: True" in out and "Stretch to 640x640" in out
    assert "  images   : 4 in the project - 2 labeled, 1 marked null, 1 not looked at yet" in out
    assert "  entering : 3 frame(s)" in out
    assert "  version  : this generation will be 2" in out
    assert "[!] 1 frame(s) have no decision yet" in out
    # Warned, not blocked - and the null is counted as a decision, which is the whole reason the
    # count is read through `state_of` rather than from a truthiness test on `annotations`.
    assert fake.posts == [generate_version.version_settings()]


