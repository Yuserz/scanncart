class _Resp:
    """Just enough of an httpx response for `generate_version.main`."""

    def __init__(self, status_code=200, body=None):
        self.status_code = status_code
        self._body = {} if body is None else body

    def json(self):
        return self._body


def _annotated(labeled: int = 3, nulls: int = 0, unlabeled: int = 0) -> dict[str, dict]:
    """Project records as the search route returns them, in the three states that matter.

    The state is the *type* of `annotations`, which is the whole trick: a **list** means nobody has
    looked, and a dict with `count: 0` is a null annotation - the hard negatives, a decision.
    """
    records: dict[str, dict] = {}
    for index in range(labeled):
        records[f"labeled_{index}.jpg"] = {
            "name": f"labeled_{index}.jpg",  # the sweep indexes by name, as the API answers
            "annotations": {"count": 1, "classes": {label_classes.SLUG_TO_CLASS["milo"]: 1}},
        }
    for index in range(nulls):
        records[f"null_{index}.jpg"] = {
            "name": f"null_{index}.jpg",
            "annotations": {"count": 0, "classes": {}},
        }
    for index in range(unlabeled):
        records[f"unlabeled_{index}.jpg"] = {"name": f"unlabeled_{index}.jpg", "annotations": []}
    return records


class _FakeRoboflow:
    """The three routes `--yes` touches: the project read, the annotation search, and the POST."""

    def __init__(self, project_body, records=None, search_body=None):
        self.project_body = project_body
        self.records = records if records is not None else {}
        # An override for the *search* response, so a route that will not answer is testable.
        self.search_body = search_body
        self.posts: list = []

    # `generate_version` calls `httpx.get`/`httpx.post` on the module, while
    # `label_progress.project_states` opens `httpx.Client(...)` - so the double stands in for both
    # by handing back itself as the client.
    def Client(self, **_kwargs):  # noqa: N802 - named after the httpx API it replaces
        return self

    def __enter__(self):
        return self

    def __exit__(self, *_exc):
        return False

    def get(self, url, **_kwargs):
        return _Resp(200, self.project_body)

    def post(self, url, **kwargs):
        if "/search" in url:
            if self.search_body is not None:
                return _Resp(200, self.search_body)
            return _Resp(200, {"results": list(self.records.values()), "total": len(self.records)})
        self.posts.append(kwargs.get("json"))
        return _Resp(200, {"version": 2, "message": "building"})


def _generator(monkeypatch, classes: dict, records=None, search_body=None) -> _FakeRoboflow:
    fake = _FakeRoboflow(
        {"project": {"classes": classes}, "versions": [{"id": "ws/proj/1"}]},
        _annotated() if records is None else records,
        search_body,
    )
    monkeypatch.setattr(generate_version, "load_key", lambda _project: "k")
    monkeypatch.setattr(generate_version, "httpx", fake)
    # The preflight's image count reads the project through `label_progress`, which owns the
    # three-state rule - so the same fake has to stand in for that module's httpx too.
    monkeypatch.setattr(label_progress, "httpx", fake)
    return fake


def test_the_generator_refuses_a_class_list_with_a_distance_in_it(monkeypatch, capsys):
    """The whole point of the preflight: a version generated from a distance-split class list
    trains one head output per product-and-distance, and a version number cannot be reused -
    so this refuses and spends nothing.
    """
    fake = _generator(
        monkeypatch,
        {
            "Palmolive Naturals Bar Soap 85g close": 1,
            "Palmolive Naturals Bar Soap 85g mid": 2,
            "Palmolive Naturals Bar Soap 85g far": 3,
            "Milo Chocolate Drink 22g Sachet": 4,
        },
    )

    assert generate_version.main(["--yes", "--project", "snc-grocery"]) == 2
    # Nothing was sent, so nothing was spent - that is the difference between a refusal and
    # a warning printed after the fact.
    assert fake.posts == []
    out = capsys.readouterr().out
    assert "refusing to generate" in out
    assert "'Palmolive Naturals Bar Soap 85g mid'" in out
    assert "MOVE" in out and "no version number was spent" in out


